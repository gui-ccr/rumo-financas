export type CategoryIconKey = keyof typeof CATEGORY_ICONS;

export const CATEGORY_ICON_KEYS = Object.keys(CATEGORY_ICONS) as CategoryIconKey[];

export function CategoryGlyph({ name, ...props }: { name: string } & LucideProps) {
  const Glyph = CATEGORY_ICONS[name as CategoryIconKey] ?? CircleDashed;
  return <Glyph {...props} />;
}
